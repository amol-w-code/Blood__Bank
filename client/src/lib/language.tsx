interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (text: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);
const STORAGE_KEY = 'bloodbridge-language';

function initialLanguage(): Language {
  const saved = window.localStorage.getItem(STORAGE_KEY) ?? window.localStorage.getItem('bloodbridge-assistant-language');
  return LANGUAGES.some((item) => item.value === saved) ? (saved as Language) : 'en';
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(initialLanguage);

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
    document.title = language === 'en'
      ? 'BloodBridge: real-time blood donation network'
      : translations[language]['BloodBridge: real-time blood donation network'] ?? 'BloodBridge';
  }, [language]);

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    t: (text) => language === 'en' ? text : translations[language][text] ?? text,
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider');
  return context;
}

export function LanguageSelector({ className = '' }: { className?: string }) {
  const { language, setLanguage, t } = useLanguage();
  return (
    <label className={`inline-flex items-center gap-2 ${className}`}>
      <span className="sr-only">{t('Website language')}</span>
      <select
        aria-label={t('Website language')}
        value={language}
        onChange={(event) => setLanguage(event.target.value as Language)}
        className="h-10 max-w-36 cursor-pointer rounded-xl border border-ink-200 bg-white px-3 text-sm font-semibold text-ink-700 focus:border-brand-400 focus:outline-none focus:ring-4 focus:ring-brand-100"
      >
        {LANGUAGES.map((item) => <option key={item.value} value={item.value}>{item.label}</option>)}
      </select>
    </label>
  );
}
